#!/bin/bash
#SBATCH -J nsys_mps
#SBATCH -N 1
#SBATCH -n 2
#SBATCH -c 1
#SBATCH --gpus=1
#SBATCH --exclusive
#SBATCH -t 02:00:00
#SBATCH -o nsys_mps_%j.out
#
# Profiles the GPU + restriction build with Nsight Systems: 2 MPI ranks sharing ONE GPU
# through MPS (enable_mps.sh), 64x32^3, method 4, 1 OpenMP thread per rank.
# The reports are packed into nsys_mps.tar.gz and the temporary folder is removed.
#
# usage:  cd /lus/bnchlu5/e75014/DDalphaAMG
#         sbatch nsys_mps_CASTNER.sh

INPUT=3lvl_sample64_CASTNER_m4.ini     # 2-rank decomposition (local lattice 32 32 32 32)
EXE=./dd_alpha_amg                     # GPU + restriction build
ARCHIVE=nsys_mps.tar.gz
NSYS_DIR=/opt/nvidia/hpc_sdk/Linux_aarch64/25.9/profilers/13.0/Nsight_Systems/target-linux-sbsa-armv8

die() { echo "ERROR: $*"; exit 1; }

cd "$SLURM_SUBMIT_DIR" || die "cannot cd to $SLURM_SUBMIT_DIR"
export PATH=$NSYS_DIR:$PATH
unset SLURM_GPUS_PER_TASK SLURM_TRES_PER_TASK

# --- checks ----------------------------------------------------------------------
command -v nsys > /dev/null                    || die "nsys not found"
command -v nvidia-cuda-mps-control > /dev/null || die "nvidia-cuda-mps-control not found"
[ -x "$EXE" ]                                  || die "$EXE not found"
ldd "$EXE" | grep -q libcudart                 || die "$EXE is not a GPU build"
strings "$EXE" | grep -q cuda_restrict         || die "$EXE does not contain the ported restriction"
[ "$(strings "$EXE" | grep -c 'restrict test')" = "0" ] || die "$EXE contains the unit test"
[ -f enable_mps.sh ]                           || die "enable_mps.sh not found"
[ -x enable_mps.sh ] || chmod +x enable_mps.sh
[ -f "$INPUT" ]                                || die "$INPUT not found"
grep -q "^d0 local lattice: 32 32 32 32" "$INPUT" || die "$INPUT is not the 2-rank decomposition"

WORK=nsys_mps_${SLURM_JOB_ID}
mkdir -p "$WORK"
cp "$INPUT" "$WORK/input.ini"

GPU_ID=${CUDA_VISIBLE_DEVICES:-0}; GPU_ID=${GPU_ID%%,*}

{
  echo "date:        $(date)"
  echo "node:        $(hostname)"
  echo "job id:      $SLURM_JOB_ID"
  echo "git commit:  $(git rev-parse --short HEAD 2>/dev/null) ($(git rev-parse --abbrev-ref HEAD 2>/dev/null))"
  echo "binary:      $EXE (GPU + restriction)"
  echo "input:       $INPUT (method $(grep '^method:' "$INPUT" | cut -d: -f2 | tr -d ' '))"
  echo "MPI ranks:   2, both on GPU $GPU_ID through MPS"
  echo "OMP threads: 1 per rank"
  echo "nsys:        $(nsys --version)"
  echo "GPU:         $(nvidia-smi --query-gpu=name,compute_mode --format=csv,noheader -i "$GPU_ID")"
} > "$WORK/info.txt"
cat "$WORK/info.txt"

# --- profiled run ----------------------------------------------------------------
# enable_mps.sh starts the MPS daemon, then runs "nsys profile ... ./dd_alpha_amg"
echo "=== profiled run started $(date +%T)"
MPICH_GPU_SUPPORT_ENABLED=1 OMP_NUM_THREADS=1 GPUSID=$GPU_ID SLURM_NTASKS_PER_NODE=2 \
  srun -n 2 -c ${SLURM_CPUS_PER_TASK:-1} --cpu-bind=cores --gpus=1 \
       ./enable_mps.sh \
       nsys profile --trace=cuda,nvtx,mpi --mpi-impl=mpich --force-overwrite=true \
                    -o "$WORK/report_rank%q{SLURM_PROCID}" \
       "$EXE" "$WORK/input.ini" > "$WORK/output.txt" 2>&1
RC=$?
echo "run exit code: $RC" | tee -a "$WORK/info.txt"

# stop the MPS daemon(s) of this job
for d in /tmp/$(id -un)/slurm-${SLURM_JOB_ID}.*/nvidia-mps; do
  [ -d "$d" ] || continue
  CUDA_MPS_PIPE_DIRECTORY=$d nvidia-cuda-mps-control <<< quit > /dev/null 2>&1
  sleep 2
  rm -rf "$(dirname "$d")"
done

# --- quick checks in the archive ---------------------------------------------------
{
  echo "iterations:  $(grep -c 'approx. rel. res' "$WORK/output.txt")"
  echo "residual:    $(grep 'exact relative residual' "$WORK/output.txt")"
  echo "CUDA errors: $(grep -ci 'cuda error' "$WORK/output.txt")"
  grep "MPS wrapper" "$WORK/output.txt"
} | tee -a "$WORK/info.txt"

# --- text summaries (readable without the GUI) -------------------------------------
for rep in "$WORK"/report_rank*.nsys-rep; do
  [ -f "$rep" ] || continue
  r=$(basename "$rep" .nsys-rep)
  nsys stats --force-export=true \
       --report cuda_gpu_kern_sum,cuda_gpu_mem_time_sum,cuda_gpu_mem_size_sum,cuda_api_sum \
       "$rep" > "$WORK/${r}_summary.txt" 2>&1
done
rm -f "$WORK"/*.sqlite          # large, regenerated by nsys stats from the .nsys-rep

# --- archive, verify, clean up -----------------------------------------------------
ls "$WORK"/report_rank*.nsys-rep > /dev/null 2>&1 || die "no .nsys-rep produced, files kept in $WORK"
tar -czf "$ARCHIVE" "$WORK"
if tar -tzf "$ARCHIVE" > /dev/null 2>&1; then
  echo "archive OK: $ARCHIVE ($(du -h "$ARCHIVE" | cut -f1))"
  tar -tzf "$ARCHIVE"
  rm -rf "$WORK"
  echo "temporary folder $WORK removed"
else
  die "archive check failed, files kept in $WORK"
fi
